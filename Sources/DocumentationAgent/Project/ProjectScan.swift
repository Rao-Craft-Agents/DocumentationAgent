//  WHAT: The project, read from disk: every code file and every Markdown file under the folders a call names (the
//        whole project when it names none), in path order, with what was passed over and why. What every make reads.
//  PIN:  CAPPED, AND SAYS SO. A file over `maxFileBytes`, past `maxTotalBytes` of text, or past `maxFiles` is left out
//        and listed in `skipped` with the reason, so a project with a vendored blob or a generated data file still
//        documents in seconds and the answer tells the person what is missing.
//  PIN:  NEVER ITS OWN OUTPUT. A folder a site from this package already lives in (its data says so on its first line)
//        is not read, and neither is the folder a call writes into, so a second run reads the same tree as the first.

import Foundation

struct ProjectScan: Sendable {
    static let maxFileBytes = 400_000
    static let maxDocBytes = 200_000
    static let maxTotalBytes = 24_000_000
    static let maxFiles = 8_000
    /// Folders never read: tools' caches, dependencies, build products, editor state, bundles of assets.
    static let skippedFolders: Set<String> = [".git", ".build", ".swiftpm", "node_modules", "DerivedData", "Pods", "Carthage", "build",
                                              "dist", ".next", "vendor", "__pycache__", "xcuserdata", ".idea", ".vscode", "coverage",
                                              ".gradle", "target", ".venv", "venv", ".tox", ".mypy_cache", ".pytest_cache"]
    static let skippedSuffixes = [".xcodeproj", ".xcworkspace", ".xcassets", ".xcdatamodeld", ".lproj", ".app", ".framework",
                                  ".xcframework", ".bundle", ".dSYM", ".playground", ".docc", ".icon"]
    static let generatedMark = "generated by DocumentationAgent"

    let root: URL
    private(set) var files: [ProjectFile] = []
    private(set) var docs: [ProjectFile] = []
    private(set) var skipped: [(path: String, why: String)] = []

    /// Reads `root`, or only `sources` under it, leaving out `exclude` (paths from the root).
    init(root: URL, sources: [String], exclude: [String]) {
        self.root = root
        let manager = FileManager.default
        let rootPath = root.path.hasSuffix("/") ? String(root.path.dropLast()) : root.path
        let excluded = Set(exclude.map { $0.hasSuffix("/") ? String($0.dropLast()) : $0 })
        var found: [(path: String, url: URL)] = []
        var seen: Set<String> = []
        func visit(_ url: URL, _ rel: String) {
            var isFolder: ObjCBool = false
            guard manager.fileExists(atPath: url.path, isDirectory: &isFolder) else { return }
            if !isFolder.boolValue {
                if seen.insert(rel).inserted { found.append((rel, url)) }
                return
            }
            if !rel.isEmpty {
                let name = url.lastPathComponent
                if excluded.contains(rel) || Self.skippedFolders.contains(name) || name.hasPrefix(".")
                    || Self.skippedSuffixes.contains(where: { name.hasSuffix($0) }) || Self.isGeneratedSite(url) { return }
            }
            guard let names = try? manager.contentsOfDirectory(atPath: url.path) else { return }
            for name in names.sorted() where !name.hasPrefix(".") {
                visit(url.appendingPathComponent(name), rel.isEmpty ? name : rel + "/" + name)
            }
        }
        if sources.isEmpty {
            visit(URL(fileURLWithPath: rootPath, isDirectory: true), "")
        } else {
            for source in sources {
                let rel = Self.relative(source, root: rootPath)
                visit(URL(fileURLWithPath: rootPath + (rel.isEmpty ? "" : "/" + rel)), rel)
            }
        }
        found.sort { $0.path < $1.path }
        var total = 0
        for (path, url) in found {
            let ext = (path as NSString).pathExtension.lowercased()
            let isDoc = ext == "md" || ext == "markdown"
            guard isDoc || ProjectFile.languages[ext] != nil else { continue }
            let size = (try? url.resourceValues(forKeys: [.fileSizeKey]).fileSize) ?? 0
            if size > (isDoc ? Self.maxDocBytes : Self.maxFileBytes) {
                skipped.append((path, "it is \(size / 1000) KB, over the \((isDoc ? Self.maxDocBytes : Self.maxFileBytes) / 1000) KB a file may be"))
                continue
            }
            if files.count + docs.count >= Self.maxFiles {
                skipped.append((path, "the project has more than \(Self.maxFiles) files to read"))
                continue
            }
            if total + size > Self.maxTotalBytes {
                skipped.append((path, "the files before it hold \(Self.maxTotalBytes / 1_000_000) MB of text, all a site carries"))
                continue
            }
            guard let data = try? Data(contentsOf: url), let text = String(data: data, encoding: .utf8) ?? String(data: data, encoding: .isoLatin1) else {
                skipped.append((path, "it could not be read as text"))
                continue
            }
            total += size
            if isDoc { docs.append(ProjectFile(path: path, language: "Markdown", text: text)) }
            else { files.append(ProjectFile(path: path, language: ProjectFile.languages[ext]!, text: text)) }
        }
    }

    /// `path` from the root: a relative path cleaned, or an absolute one inside the root made relative.
    static func relative(_ path: String, root: String) -> String {
        let expanded = (path as NSString).expandingTildeInPath
        let absolute = expanded.hasPrefix("/") ? AgentFiles.resolvingParents(expanded) : AgentFiles.resolvingParents(root + "/" + expanded)
        if absolute == root { return "" }
        return absolute.hasPrefix(root + "/") ? String(absolute.dropFirst(root.count + 1)) : absolute
    }

    /// Whether `folder` holds a site this package wrote: its data says so on its first line.
    static func isGeneratedSite(_ folder: URL) -> Bool {
        let data = folder.appendingPathComponent("data.js")
        guard let handle = try? FileHandle(forReadingFrom: data) else { return false }
        defer { try? handle.close() }
        let head = String(decoding: (try? handle.read(upToCount: 200)) ?? Data(), as: UTF8.self)
        return head.contains(generatedMark)
    }

    var swiftFiles: [ProjectFile] { files.filter(\.isSwift) }
}
