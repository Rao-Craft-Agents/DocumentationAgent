//  WHAT: The site's `data.js`: the project as its pages read it, one classic script that sets `window.DOCS_SITE`
//        (`fetch` is refused on `file://`): its folders with what each one is, its files with what each says, its
//        Markdown docs, how it is built, its services and components, its types and its trails.
//  PIN:  DETERMINISTIC. Every map is sorted, no clock is read, and the only revision named is the project's own commit,
//        so the same tree writes the same bytes.

import Foundation

enum SiteData {
    static let header = "/* generated by DocumentationAgent (docs) - do not edit; ask the docs agent for the site again */\n"

    static func script(_ model: ProjectModel, trails: [Trail], site: String, tagline: String?, ask: Bool, build: BuildFacts) -> String {
        header + "window.DOCS_SITE = " + value(model, trails: trails, site: site, tagline: tagline, ask: ask, build: build).text + ";\n"
    }

    static func value(_ model: ProjectModel, trails: [Trail], site: String, tagline: String?, ask: Bool, build: BuildFacts) -> JSONValue {
        let graph = model.graph
        let scopes = graph?.scopes.count ?? 0
        let counts: JSONValue = .object([
            ("files", .int(model.scan.files.count)), ("swift", .int(model.swift.count)),
            ("lines", .int(model.scan.files.reduce(0) { $0 + $1.lines })), ("declarations", .int(scopes)),
            ("edges", .int(graph?.edges.count ?? 0)), ("services", .int(model.services.count)), ("components", .int(model.components.count)),
            ("docs", .int(model.scan.docs.count)), ("trails", .int(trails.count)),
        ])
        let meta: JSONValue = .object([
            ("title", .string(model.title)), ("tagline", .optional(tagline)), ("generator", .string("DocumentationAgent")),
            ("head", .optional(model.head)), ("site", .string(site)), ("ask", .bool(ask)), ("counts", counts),
            ("skipped", .array(model.scan.skipped.prefix(200).map { .array([.string($0.path), .string($0.why)]) })),
        ])
        return .object([
            ("meta", meta),
            ("spine", .strings(spine(model))),
            ("folders", folders(model)),
            ("files", .array(model.scan.files.map { file(model, $0) })),
            ("docs", .sorted(Dictionary(uniqueKeysWithValues: model.scan.docs.map { doc in
                (doc.path, JSONValue.object([("title", .string(title(of: doc))), ("text", .string(doc.text)), ("lines", .int(doc.lines))]))
            }))),
            ("build", buildValue(model, build)),
            ("services", .array(model.services.map(host))),
            ("components", .array(model.components.map(host))),
            ("cycles", .strings(model.cycles)),
            ("types", types(model)),
            ("trails", .array(trails.map { .object([("id", .string($0.id)), ("title", .string($0.title)), ("subtitle", .string($0.subtitle)),
                                                     ("say", .string($0.say)), ("mark", .string($0.mark))]) })),
        ])
    }

    /// The folders at the top of the project that hold a file read, in name order.
    static func spine(_ model: ProjectModel) -> [String] {
        (model.folders["."]?.folders ?? []).sorted { $0.lowercased() < $1.lowercased() }
    }

    static func title(of doc: ProjectFile) -> String {
        for line in doc.text.components(separatedBy: "\n") where line.hasPrefix("# ") {
            return line.dropFirst(2).trimmingCharacters(in: .whitespaces).replacingOccurrences(of: #"\s+#+$"#, with: "", options: .regularExpression)
        }
        return doc.name
    }

    static func folders(_ model: ProjectModel) -> JSONValue {
        var map: [String: JSONValue] = [:]
        for (path, f) in model.folders {
            let about: JSONValue = f.about.map { a in
                .object([("text", .string(a.text)), ("from", .string(a.from)), ("source", .optional(a.source)), ("line", .optional(a.line)), ("type", .optional(a.type))])
            } ?? .null
            let root: JSONValue = f.rootType.map { r in .object([("name", .string(r.name)), ("path", .string(r.path)), ("line", .int(r.line)), ("kind", .string(r.kind))]) } ?? .null
            map[path] = .object([
                ("name", .string(f.name)), ("parent", .optional(f.parent)), ("kind", .string(f.kind)), ("folders", .strings(f.folders)),
                ("files", .strings(f.files)),
                ("counts", .object([("files", .int(f.files1)), ("lines", .int(f.lines1)), ("filesAll", .int(f.filesAll)), ("linesAll", .int(f.linesAll)),
                                    ("foldersAll", .int(f.foldersAll))])),
                ("about", about), ("holds", .optional(f.holds)), ("rootType", root), ("services", .strings(f.services)), ("components", .strings(f.components)),
                ("package", .optional(f.package)),
            ])
        }
        return .sorted(map)
    }

    static func file(_ model: ProjectModel, _ file: ProjectFile) -> JSONValue {
        var summary = ""
        var decls: [JSONValue] = []
        var module = file.topFolder == "." ? model.title : file.topFolder
        if file.isSwift, let source = model.swiftSource(file.path) {
            summary = source.summary
            module = source.module
            for scope in source.scopes.prefix(400) where scope.flags & SwiftScope.localFlag == 0 {
                decls.append(.array([.string(scope.keyword), .string(scope.name), .int(scope.sig), .int(scope.parent < 0 ? 0 : 1)]))
            }
        } else {
            summary = OtherSource.summary(file)
        }
        return .object([("path", .string(file.path)), ("lang", .string(file.language)), ("lines", .int(file.lines)), ("summary", .string(summary)),
                        ("module", .string(module)), ("decls", .array(decls))])
    }

    static func buildValue(_ model: ProjectModel, _ build: BuildFacts) -> JSONValue {
        let swift: [JSONValue] = model.manifest.packages.map { p in
            .object([
                ("name", .string(p.name)), ("folder", .string(p.folder)), ("tools", .optional(p.toolsVersion)), ("platforms", .strings(p.platforms)),
                ("products", .array(p.products.map { .object([("kind", .string($0.kind)), ("name", .string($0.name)), ("targets", .strings($0.targets))]) })),
                ("dependencies", .array(p.dependencies.map { .object([("name", .string($0.name)), ("url", .optional($0.url)), ("path", .optional($0.path)),
                                                                       ("requirement", .optional($0.requirement))]) })),
                ("targets", .array(p.targets.map { t in
                    .object([("name", .string(t.name)), ("kind", .string(t.kind)), ("folder", .string(p.sourceFolder(t))), ("layer", .int(t.layer)),
                             ("targets", .strings(t.targets)), ("products", .array(t.products.map { .strings([$0.name, $0.package]) }))])
                })),
                ("layers", .array(p.layers.map(JSONValue.strings))),
            ])
        }
        let xcode: [JSONValue] = model.manifest.xcode.map { x in
            .object([
                ("path", .string(x.path)), ("name", .string(x.name)),
                ("targets", .array(x.targets.map { .object([("name", .string($0.name)), ("kind", .string($0.kind)), ("sdk", .optional($0.sdk))]) })),
                ("schemes", .array(x.schemes.map { .object([("name", .string($0.name)), ("target", .optional($0.target)), ("tests", .bool($0.tests)),
                                                            ("destination", .optional(x.destination($0)))]) })),
                ("packages", .array(x.packages.map { .object([("name", .string($0.name)), ("url", .optional($0.url)), ("path", .optional($0.path)),
                                                              ("requirement", .optional($0.requirement))]) })),
                ("deployment", .sorted(x.deployment.mapValues(JSONValue.string))), ("swift", .optional(x.swiftVersion)),
            ])
        }
        let command = { (c: BuildFacts.Command) -> JSONValue in .object([("title", .string(c.title)), ("command", .string(c.command))]) }
        return .object([("swift", .array(swift)), ("xcode", .array(xcode)), ("requirements", .strings(build.requirements)),
                        ("build", .array((build.build + build.packageCommands.filter { !$0.title.hasSuffix("tests") }).map(command))),
                        ("test", .array((build.test + build.packageCommands.filter { $0.title.hasSuffix("tests") }).map(command)))])
    }

    static func host(_ s: ServiceFacts) -> JSONValue {
        .object([
            ("name", .string(s.name)), ("module", .string(s.module)), ("path", .string(s.path)), ("line", .int(s.line)), ("folder", .string(s.folder)),
            ("what", .optional(s.what.map(SwiftSource.firstSentence))), ("rank", .int(s.rank)), ("relays", .strings(s.relays)), ("reaches", .strings(s.reaches)),
            ("events", .array(s.events.map { e in
                .object([("event", .string(e.event)), ("reducer", .string(e.reducer)), ("path", .optional(e.path)), ("line", .optional(e.line)),
                         ("doc", .optional(e.doc))])
            })),
            ("agents", .array(s.agents.map { .object([("name", .string($0.name)), ("type", .string($0.type)), ("policy", .string($0.policy))]) })),
        ])
    }

    static func types(_ model: ProjectModel) -> JSONValue {
        guard let graph = model.graph else { return .object([]) }
        var map: [String: [JSONValue]] = [:]
        for g in graph.scopes.indices where graph.scopes[g].isType {
            let scope = graph.scopes[g]
            var pairs: [(String, JSONValue)] = [("path", .string(graph.files[graph.fileOf[g]].path)), ("line", .int(scope.sig)), ("kind", .string(scope.keyword))]
            if scope.parent >= 0 { pairs.append(("nested", .bool(true))) }
            map[scope.name, default: []].append(.object(pairs))
        }
        return .sorted(map.mapValues(JSONValue.array))
    }
}
