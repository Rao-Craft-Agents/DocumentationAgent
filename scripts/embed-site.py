#!/usr/bin/env python3
"""WHAT:  Regenerate Sources/DocumentationAgent/Site/SiteAssets+<Name>.swift from site-src/: each front-end file of the
       site as one Swift raw string literal, so the package carries its site with no resource bundle.
IN:    site-src/index.html, app.css, core.js, folders.js, explorer.js, ask.js, app.js.
OUT:   Sources/DocumentationAgent/Site/SiteAssets+Index.swift, +CSS, +Core, +Folders, +Explorer, +Ask, +App.
PIN:   THE LITERAL IS THE FILE. Each literal's value is the file's bytes exactly: a raw string with enough `#`s that
       neither its closing delimiter nor an escape can occur inside, opened and closed on lines of their own.
       SiteAssetsTests fails when a literal and its file differ, so edit site-src/ and run this script.
USAGE: python3 -I scripts/embed-site.py
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "site-src"
OUT = ROOT / "Sources" / "DocumentationAgent" / "Site"
# The file, the Swift name of its literal, and the file the literal goes in.
FILES = [("index.html", "index", "Index"), ("app.css", "css", "CSS"), ("core.js", "core", "Core"), ("folders.js", "folders", "Folders"),
         ("explorer.js", "explorer", "Explorer"), ("ask.js", "ask", "Ask"), ("app.js", "app", "App")]


def literal(text):
    hashes = 1
    while ('"""' + "#" * hashes) in text or ("\\" + "#" * hashes) in text:
        hashes += 1
    mark = "#" * hashes
    return mark + '"""\n' + text + '\n"""' + mark


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    written = 0
    for name, symbol, suffix in FILES:
        text = (SOURCE / name).read_text(encoding="utf-8")
        swift = ("// GENERATED by scripts/embed-site.py from site-src/" + name + " - do not edit; edit site-src/ and run the script.\n\n"
                 "extension SiteAssets {\n"
                 "    /// site-src/" + name + ", whole.\n"
                 "    static let " + symbol + " = " + literal(text) + "\n"
                 "}\n")
        path = OUT / ("SiteAssets+" + suffix + ".swift")
        if not path.exists() or path.read_text(encoding="utf-8") != swift:
            path.write_text(swift, encoding="utf-8")
            written += 1
    print(f"embed-site: {written} of {len(FILES)} files rewritten in {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
